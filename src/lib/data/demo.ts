export function getDemoProcurementRecords(
  query: NormalizedProcurementSearchQuery,
  scope?: { resource?: ProcurementResource; kind?: ProcurementKind },
): ProcurementRecord[] {
  const keyword = query.keyword?.trim().toLocaleLowerCase("ko-KR");
  const bidNoticeNo = query.bidNoticeNo?.trim().toLocaleLowerCase("ko-KR");

  return DEMO_RECORDS.filter((record) => {
    if (!query.resources.includes(record.resource) || !query.kinds.includes(record.kind)) return false;
    if (scope?.resource && record.resource !== scope.resource) return false;
    if (scope?.kind && record.kind !== scope.kind) return false;
    if (bidNoticeNo && !record.bidNoticeNo?.toLocaleLowerCase("ko-KR").includes(bidNoticeNo)) return false;
    if (!keyword) return true;

    return [record.title, record.organization, record.demandOrganization, record.winnerName]
      .some((value) => value?.toLocaleLowerCase("ko-KR").includes(keyword));
  });
}
